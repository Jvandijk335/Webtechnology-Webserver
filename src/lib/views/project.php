    <h2>About our Web Technologies Project</h2>
    <p>Welcome to our game website! This project was developed as part of the Web Technologies course. Within this project, we created an interactive game, including a leaderboard that tracks player results.</p>

    <h2>Project Goal</h2>
    <p>The goal of the project is to gain hands-on experience in designing, building, and hosting a complete web application on a Linux server. During this project, we learned to work with web development, server management, databases, API design, and teamwork.</p>

    <h2>Key Components</h2>
    <ul>
        <li>🔧 Web server installation (HTTP/HTTPS)</li>
        <li>📄 Frontend development using HTML, CSS, and JavaScript</li>
        <li>🧠 Backend via PHP with dynamic pages</li>
        <li>💾 Database integration and protection against SQL injections</li>
        <li>🔗 RESTful API design for communication between client and server</li>
        <li>👥 Version control with Git and collaboration via GitHub</li>
        <li>📡 Communication with an external embedded device via REST API</li>
        <li>📊 Leaderboard page displaying live data from the database</li>
        <li>🧾 Ability to export database data in various formats</li>
    </ul>

    <h2>What Did We Learn?</h2>
    <p>We learned how to develop and host a secure, scalable, and functional web application. By using Git and GitHub, we were able to collaborate effectively and document our progress. We also gained experience with RESTful principles and how an external device can deliver data to our server.</p>

    <h2>In Conclusion</h2>
    <p>It was an educational project where theory and practice came together perfectly. Our game with leaderboard is live and serves as a great example of what we can achieve with web technologies.</p>
