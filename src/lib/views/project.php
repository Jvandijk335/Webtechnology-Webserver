        <h2>About our Web Technologies Project</h2>
        <p>Welkom op onze game-website! Dit project is ontwikkeld als onderdeel van het Web Technologies vak. Binnen dit project hebben we een interactieve game gemaakt, inclusief een leaderboard dat spelersresultaten bijhoudt.</p>

        <h2>Doel van het Project</h2>
        <p>Het doel van het project is om praktijkervaring op te doen met het ontwerpen, bouwen en hosten van een volledige webapplicatie op een Linux-server. Tijdens dit project leerden we werken met web development, serverbeheer, databases, API-design en teamwork.</p>

        <h2>Belangrijke Onderdelen</h2>
        <ul>
            <li>🔧 Webserver installatie (HTTP/HTTPS)</li>
            <li>📄 Frontend ontwikkeling met HTML, CSS en JavaScript</li>
            <li>🧠 Backend via PHP met dynamische pagina's</li>
            <li>💾 Database-integratie en beveiliging tegen SQL-injecties</li>
            <li>🔗 RESTful API ontwerp voor communicatie tussen client en server</li>
            <li>👥 Versiebeheer met Git en samenwerking via GitHub</li>
            <li>📡 Communicatie met een extern embedded device via REST API</li>
            <li>📊 Leaderboard pagina die live data toont vanuit de database</li>
            <li>🧾 Mogelijkheid om databasegegevens te exporteren in verschillende formaten</li>
        </ul>

        <h2>Wat hebben we geleerd?</h2>
        <p>We hebben geleerd hoe we een veilige, schaalbare en functionele webapplicatie kunnen ontwikkelen en hosten. Door gebruik te maken van Git en GitHub hebben we effectief kunnen samenwerken en onze voortgang gedocumenteerd. Ook hebben we ervaring opgedaan met RESTful principes en hoe een externe device data kan aanleveren aan onze server.</p>

        <h2>Tot Slot</h2>
        <p>Het was een leerzaam project waarin theorie en praktijk perfect samenkwamen. Onze game met leaderboard is live en vormt een mooi voorbeeld van wat we met webtechnologieën kunnen bereiken.</p>
